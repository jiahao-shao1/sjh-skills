create_file "scripts/benchmark/validate_paper_results.py" '#!/usr/bin/env python3
"""Validate docs/paper-results/results.yaml schema and source paths.

Checks:
- Each entry has required fields (paper_key, exp_id, benchmark, value, ...)
- source_registry and source_output paths exist
- paper_key uniqueness
- value matches correct / total when both are integers

Stub generated by init-project skill. Extend per project schema.
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

MANIFEST = Path("docs/paper-results/results.yaml")
REQUIRED_FIELDS = (
    "paper_key",
    "exp_id",
    "benchmark",
    "value",
    "source_registry",
    "status",
    "date",
)


def main() -> int:
    if not MANIFEST.exists():
        print(f"[error] {MANIFEST} not found", file=sys.stderr)
        return 1

    data = yaml.safe_load(MANIFEST.read_text()) or {}
    entries = data.get("results") or []
    if not entries:
        print(f"[warn] {MANIFEST} has no results entries")
        return 0

    errors: list[str] = []
    seen_keys: set[str] = set()

    for idx, entry in enumerate(entries):
        prefix = f"entry[{idx}]"
        if not isinstance(entry, dict):
            errors.append(f"{prefix}: not a mapping")
            continue
        for field in REQUIRED_FIELDS:
            if field not in entry:
                errors.append(f"{prefix}: missing field {field!r}")
        key = entry.get("paper_key")
        if key in seen_keys:
            errors.append(f"{prefix}: duplicate paper_key {key!r}")
        elif key:
            seen_keys.add(key)
        for path_field in ("source_registry", "source_output"):
            src = entry.get(path_field)
            if src and not Path(src).exists():
                errors.append(f"{prefix}: {path_field} {src!r} does not exist")

    if errors:
        print("[fail] manifest validation errors:", file=sys.stderr)
        for err in errors:
            print(f"  - {err}", file=sys.stderr)
        return 1

    print(f"[ok] {len(entries)} entries validated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'

create_file "scripts/benchmark/generate_paper_results.py" '#!/usr/bin/env python3
"""Generate paper/generated/results_macros.tex from results.yaml.

Each manifest entry produces a LaTeX macro:

    \\providecommand{\\Result<PaperKey>}{<value>}

Paper tables and prose should reference these macros instead of hand-written
numbers. Stub generated by init-project skill.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

MANIFEST = Path("docs/paper-results/results.yaml")
OUTPUT = Path("paper/generated/results_macros.tex")


def _macro_name(paper_key: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", paper_key)
    return "Result" + "".join(p.capitalize() for p in parts if p)


def main() -> int:
    if not MANIFEST.exists():
        print(f"[error] {MANIFEST} not found", file=sys.stderr)
        return 1
    data = yaml.safe_load(MANIFEST.read_text()) or {}
    entries = data.get("results") or []
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "% Auto-generated from docs/paper-results/results.yaml",
        "% DO NOT EDIT BY HAND — run scripts/benchmark/generate_paper_results.py",
        "",
    ]
    for entry in entries:
        if not isinstance(entry, dict):
            continue
        key = entry.get("paper_key")
        value = entry.get("value")
        if key is None or value is None:
            continue
        lines.append(f"\\providecommand{{\\{_macro_name(key)}}}{{{value}}}")
    lines.append("")
    OUTPUT.write_text("\n".join(lines))
    print(f"[ok] wrote {len(entries)} macros to {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'

