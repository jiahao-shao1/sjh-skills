create_file "docs/paper-results/README.md" '# Paper Results Manifest

`results.yaml` is the only source of truth for benchmark numbers that enter the
paper. Raw benchmark outputs remain in `outputs/`, and experiment history
remains in `docs/experiment-registry/registry/`; this directory is the narrow
paper-facing layer.

## Three-tier sources of truth

1. **Raw outputs** (`outputs/`) — evidence only, never cited directly in paper
2. **Experiment registry** (`docs/experiment-registry/registry/*.yaml`) — full
   history, may contain stale / legacy / diagnostic / canonical entries
3. **Paper manifest** (`docs/paper-results/results.yaml`) — only canonical
   numbers allowed into paper tables and prose

## Workflow

```bash
# Validate manifest schema and that source paths exist
python3 scripts/benchmark/validate_paper_results.py

# Regenerate paper/generated/results_macros.tex from manifest
python3 scripts/benchmark/generate_paper_results.py
```

Paper tables and paragraphs should reference the generated macros rather than
hand-written numbers.

## Entry schema

Each `results` entry must include at minimum:

```yaml
- paper_key: "main_table.method_a.benchmark_x"  # macro lookup key
  exp_id: exp01a                                # registry pointer
  benchmark: benchmark_x
  eval_mode: <mode>                             # e.g. agent / direct / think
  value: 73.50
  correct: 1234
  total: 1678
  source_registry: docs/experiment-registry/registry/exp01a.yaml
  source_output: outputs/exp01a/benchmark_x/results.json
  status: canonical
  date: YYYY-MM-DD
  notes: |
    Free-form audit notes
```

Registry may keep multiple historical numbers; manifest must pick exactly one
canonical number per `paper_key`. When manifest and registry diverge, manifest
is the paper-facing truth and the divergence must be explained in `notes`.'

